"""Migrations are reversible, match the ORM models, and handle rows that already exist.

Synchronous on purpose: Alembic's async env.py starts its own event loop.
"""

import asyncio
import uuid

from alembic import command
from alembic.config import Config
from sqlalchemy import text

from app.core.config import Settings
from app.core.db import create_engine


def test_downgrade_then_upgrade_round_trip(alembic_config: Config) -> None:
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")


def test_models_match_migrations(alembic_config: Config) -> None:
    # Raises AutogenerateDiffsDetected if a model changed without a migration.
    command.check(alembic_config)


OLD_SCHEMA_ROWS = """
    INSERT INTO workflow_templates (id, name, definition) VALUES (:template_id, 't', '{}');
    INSERT INTO workflow_runs (id, template_id) VALUES (:run_id, :template_id);
    INSERT INTO tasks (id, run_id, key, name) VALUES
        (gen_random_uuid(), :run_id, 'b', 'B'),
        (gen_random_uuid(), :run_id, 'c', 'C'),
        (gen_random_uuid(), :run_id, 'a', 'A');
"""


async def _run_sql(database_url: str, sql: str, **parameters: object) -> list[tuple[object, ...]]:
    engine = create_engine(database_url)
    rows: list[tuple[object, ...]] = []
    try:
        async with engine.begin() as conn:
            # asyncpg sends one statement per call, so a script is split on its semicolons.
            for statement in filter(None, (part.strip() for part in sql.split(";"))):
                result = await conn.execute(text(statement), parameters)
                rows = [tuple(row) for row in result] if result.returns_rows else rows
    finally:
        await engine.dispose()
    return rows


def test_0002_numbers_existing_tasks(alembic_config: Config, test_settings: Settings) -> None:
    """A migration that adds a required column must cope with rows written before it existed."""
    url = test_settings.database_url
    command.downgrade(alembic_config, "0001")
    try:
        asyncio.run(_run_sql(url, "TRUNCATE workflow_templates CASCADE"))
        asyncio.run(_run_sql(url, OLD_SCHEMA_ROWS, template_id=uuid.uuid4(), run_id=uuid.uuid4()))
    finally:
        command.upgrade(alembic_config, "head")

    # One statement inserted all three tasks, so created_at ties and the key decides the order.
    positions = asyncio.run(_run_sql(url, "SELECT key, position FROM tasks ORDER BY key"))
    assert positions == [("a", 0), ("b", 1), ("c", 2)]
